# -*- coding: utf-8 -*-
"""
Discord自動投稿の見た目の共通原則(2026-10-06)。

  1. 見出しは太字1行まで。「#」見出しは文字が巨大になり縦長にもなるので使わない
  2. 補足(時刻・出典・注意書き)は「-#」の小さな灰色文字か、Embedのfooterにまとめる
  3. 絵文字は1投稿に最大1個。色は異常・障害のときだけ、控えめな赤を使う
  4. 階層は「重要情報(見出し)→内容(本文・箇条書き)→補足(小さな文字)」の順
  5. 技術的な生エラー(JSON・APIの応答全文)はDiscordに出さない。詳細はログに残す

Discordの標準文字サイズは変えられないため、Markdown/Embedの構造と文章量で整える。
ニュース・ローカル・市場・防災の分類はこのモジュールでは混ぜない(見た目の部品だけを共有する)。
"""

ALERT_COLOR = 0xC4453C  # 異常・障害だけに使う控えめな赤(派手な 0xE53E3E は防災速報の赤枠用に別管理)


def heading(text):
    """見出し(太字・標準サイズ)。"""
    return f"**{text}**"


def subtext(text):
    """補足(小さな灰色文字)。"""
    return f"-# {text}"


def bullet_link(title, url):
    """記事リスト1行(タイトルは標準サイズ、リンクのプレビューは出さない)。"""
    return f"- [{title}](<{url}>)"
